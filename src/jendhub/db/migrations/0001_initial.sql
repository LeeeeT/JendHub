CREATE TABLE base_releases (
    tag text PRIMARY KEY,
    source bytea NOT NULL,
    stored_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE packages (
    hash text PRIMARY KEY CHECK (hash ~ '^0x[0-9a-f]{32}$'),
    sequence bigint GENERATED ALWAYS AS IDENTITY UNIQUE,
    name text,
    version text,
    version_order numeric[] GENERATED ALWAYS AS (string_to_array(version, '.')::numeric[]) STORED,
    stored_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((name IS NULL) = (version IS NULL))
);

CREATE UNIQUE INDEX packages_release ON packages (name, version) WHERE name IS NOT NULL;

CREATE TABLE package_files (
    hash text NOT NULL REFERENCES packages ON DELETE CASCADE,
    path text NOT NULL,
    content bytea NOT NULL,
    PRIMARY KEY (hash, path)
);

CREATE TABLE rejected_packages (
    hash text PRIMARY KEY CHECK (hash ~ '^0x[0-9a-f]{32}$'),
    reason text NOT NULL,
    rejected_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE invalid_releases (
    hash text PRIMARY KEY REFERENCES packages,
    base_tag text NOT NULL REFERENCES base_releases,
    reason text NOT NULL,
    found_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE embeddings (
    model text NOT NULL,
    digest bytea NOT NULL,
    vector bytea NOT NULL,
    PRIMARY KEY (model, digest)
);

CREATE TABLE generations (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    corpus text NOT NULL,
    base_tag text NOT NULL REFERENCES base_releases,
    indexer_version integer NOT NULL,
    state text NOT NULL DEFAULT 'building' CHECK (state IN ('building', 'live', 'retired')),
    created_at timestamptz NOT NULL DEFAULT now(),
    retired_at timestamptz
);

CREATE UNIQUE INDEX generations_live ON generations (corpus) WHERE state = 'live';

CREATE TABLE collections (
    name text PRIMARY KEY,
    generation bigint NOT NULL REFERENCES generations ON DELETE CASCADE,
    dimensions integer NOT NULL,
    quantization text NOT NULL
);

CREATE TABLE index_jobs (
    generation bigint NOT NULL REFERENCES generations ON DELETE CASCADE,
    release text NOT NULL,
    name text,
    state text NOT NULL DEFAULT 'queued'
        CHECK (state IN ('queued', 'running', 'done', 'superseded', 'invalid', 'failed')),
    attempts integer NOT NULL DEFAULT 0,
    run_after timestamptz NOT NULL DEFAULT now(),
    lease_until timestamptz,
    error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    PRIMARY KEY (generation, release)
);

CREATE INDEX index_jobs_ready ON index_jobs (run_after) WHERE state IN ('queued', 'running');

CREATE TABLE definitions (
    point bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generation bigint NOT NULL REFERENCES generations ON DELETE CASCADE,
    release text NOT NULL,
    id text NOT NULL,
    key text NOT NULL,
    kind text NOT NULL CHECK (kind IN ('def', 'type', 'law')),
    name text NOT NULL,
    package text,
    version text,
    module text NOT NULL,
    text text NOT NULL,
    head text NOT NULL,
    first_line integer NOT NULL,
    end_line integer NOT NULL,
    document_digest bytea NOT NULL,
    parameters jsonb,
    result jsonb,
    documented boolean NOT NULL,
    helper boolean NOT NULL,
    users integer NOT NULL,
    reached bigint[] NOT NULL DEFAULT '{}',
    external boolean NOT NULL DEFAULT false,
    UNIQUE (generation, id)
);

CREATE INDEX definitions_release ON definitions (generation, release);
CREATE INDEX definitions_key ON definitions (generation, key);
CREATE INDEX definitions_name ON definitions (generation, name);

CREATE TABLE uses (
    user_point bigint NOT NULL REFERENCES definitions ON DELETE CASCADE,
    target_point bigint NOT NULL REFERENCES definitions ON DELETE CASCADE,
    PRIMARY KEY (user_point, target_point)
);

CREATE INDEX uses_target ON uses (target_point);

CREATE TABLE external_uses (
    generation bigint NOT NULL REFERENCES generations ON DELETE CASCADE,
    user_point bigint NOT NULL REFERENCES definitions ON DELETE CASCADE,
    target_key text NOT NULL,
    PRIMARY KEY (user_point, target_key)
);

CREATE INDEX external_uses_target ON external_uses (generation, target_key);

CREATE TABLE judgments (
    request bytea PRIMARY KEY,
    query text NOT NULL,
    id text NOT NULL,
    grade smallint NOT NULL CHECK (grade BETWEEN 0 AND 3)
);

CREATE TABLE enrichments (
    window_key bytea NOT NULL,
    id text NOT NULL,
    summary text NOT NULL,
    queries jsonb NOT NULL,
    role text NOT NULL,
    PRIMARY KEY (window_key, id)
);

CREATE TABLE enrichment_rejections (
    window_key bytea PRIMARY KEY,
    reason text NOT NULL
);
